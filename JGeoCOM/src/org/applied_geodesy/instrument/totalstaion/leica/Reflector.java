package org.applied_geodesy.instrument.totalstaion.leica;

import java.util.Locale;

public class Reflector {
	
	private final int id;
	private final double constant;
	private final String name;
	
	public Reflector(int id, String name, double constant) {
		this.id = id;
		this.constant = constant;
		this.name = name;
	}
	public int getId() {
		return this.id;
	}
	public double getPrismConstant() {
		return this.constant;
	}
	public String getName() {
		return this.name;
	}
	@Override
	public String toString() {
		return String.format(Locale.ENGLISH, "%s [c = %.4f]", this.name, this.constant);
	}
	@Override
	public int hashCode() {
		final int prime = 31;
		int result = 1;
		long temp;
		temp = Double.doubleToLongBits(constant);
		result = prime * result + (int) (temp ^ (temp >>> 32));
		result = prime * result + id;
		result = prime * result + ((name == null) ? 0 : name.hashCode());
		return result;
	}
	@Override
	public boolean equals(Object obj) {
		if (this == obj)
			return true;
		if (obj == null)
			return false;
		if (getClass() != obj.getClass())
			return false;
		Reflector other = (Reflector) obj;
		if (Double.doubleToLongBits(constant) != Double
				.doubleToLongBits(other.constant))
			return false;
		if (id != other.id)
			return false;
		if (name == null) {
			if (other.name != null)
				return false;
		} else if (!name.equals(other.name))
			return false;
		return true;
	}	
}
